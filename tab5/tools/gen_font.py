#!/usr/bin/env python3
"""Generate the Tab5 status font (firmware/main/font.c) from Pillow's bundled
default font (Aileron, SIL Open Font License 1.1).

    python3 -m venv .venv && .venv/bin/pip install pillow
    .venv/bin/python gen_font.py 30 > ../firmware/main/font.c

Proportional, 8-bit alpha (anti-aliased), ASCII 32..126.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

size = int(sys.argv[1]) if len(sys.argv) > 1 else 30
font = ImageFont.load_default(size=size)
ascent, descent = font.getmetrics()
height = ascent + descent

glyphs = []
for code in range(32, 127):
    ch = chr(code)
    adv = int(round(font.getlength(ch)))
    w = max(adv, 1)
    img = Image.new('L', (w, height), 0)
    ImageDraw.Draw(img).text((0, 0), ch, font=font, fill=255)
    glyphs.append((w, img.tobytes()))

out = []
out.append('// Generated by tab5/tools/gen_font.py from Pillow\'s default font')
out.append('// (Aileron, SIL Open Font License 1.1). Do not edit.')
out.append('#include "font.h"\n')
offs, data = [], bytearray()
for w, px in glyphs:
    offs.append(len(data))
    data += px
out.append('static const uint8_t ALPHA[%d] = {' % len(data))
for i in range(0, len(data), 24):
    out.append('    ' + ', '.join(str(b) for b in data[i:i + 24]) + ',')
out.append('};\n')
out.append('static const font_glyph_t GLYPHS[95] = {')
for (w, _), o in zip(glyphs, offs):
    out.append('    {%d, %d},' % (w, o))
out.append('};\n')
out.append('const font_t FONT_STATUS = {%d, %d, GLYPHS, ALPHA};' % (height, ascent))
print('\n'.join(out))
